#!/usr/bin/env python3
"""Generates src/markdown/EntityTable.inc and EntityNames.inc from Python's HTML5 character references."""

from html.entities import html5, name2codepoint
from pathlib import Path


def literal(text: str) -> str:
    out = ""
    for ch in text:
        code = ord(ch)
        if ch in '"\\':
            out += "\\" + ch
        elif ch == "\n":
            out += "\\n"
        elif ch == "\t":
            out += "\\t"
        elif code < 0x80:
            out += ch  # universal character names can't spell ASCII
        elif code <= 0xFFFF:
            out += f"\\u{code:04X}"
        else:
            out += f"\\U{code:08X}"
    return out


def main() -> None:
    # CommonMark only accepts the forms with a semicolon.
    entries = sorted((name[:-1], value) for name, value in html5.items() if name.endswith(";"))
    lines = ["// Generated by tools/generate_entities.py. Sorted by name in UTF-16 order, do not edit."]
    lines += [f'{{u"{name}", u"{literal(value)}"}},' for name, value in entries]
    directory = Path(__file__).resolve().parent.parent / "src" / "markdown"
    (directory / "EntityTable.inc").write_text("\n".join(lines) + "\n", encoding="ascii")

    # The reverse: for each text the name people know best. HTML4 names first (&hellip;, not &mldr;), then the
    # shortest, then lower case.
    best: dict[str, str] = {}
    for name, value in entries:
        rank = (name not in name2codepoint, len(name), not name.islower(), name)
        if value not in best or rank < (best[value] not in name2codepoint, len(best[value]),
                                        not best[value].islower(), best[value]):
            best[value] = name
    lines = ["// Generated by tools/generate_entities.py. Sorted by text in UTF-16 order, do not edit."]
    for value in sorted(best, key=lambda text: text.encode("utf-16-be")):
        lines.append(f'{{u"{literal(value)}", u"{best[value]}"}},')
    (directory / "EntityNames.inc").write_text("\n".join(lines) + "\n", encoding="ascii")


if __name__ == "__main__":
    main()

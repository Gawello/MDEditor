#!/usr/bin/env python3
"""Generates src/markdown/EntityTable.inc from Python's copy of the HTML5 named character references."""

from html.entities import html5
from pathlib import Path


def literal(text: str) -> str:
    out = ""
    for ch in text:
        code = ord(ch)
        if ch in '"\\':
            out += "\\" + ch
        elif ch == "\n":
            out += "\\n"
        elif ch == "\t":
            out += "\\t"
        elif code < 0x80:
            out += ch  # universal character names can't spell ASCII
        elif code <= 0xFFFF:
            out += f"\\u{code:04X}"
        else:
            out += f"\\U{code:08X}"
    return out


def main() -> None:
    # CommonMark only accepts the forms with a semicolon.
    entries = sorted((name[:-1], value) for name, value in html5.items() if name.endswith(";"))
    lines = ["// Generated by tools/generate_entities.py. Sorted by name in UTF-16 order, do not edit."]
    lines += [f'{{u"{name}", u"{literal(value)}"}},' for name, value in entries]
    target = Path(__file__).resolve().parent.parent / "src" / "markdown" / "EntityTable.inc"
    target.write_text("\n".join(lines) + "\n", encoding="ascii")


if __name__ == "__main__":
    main()
